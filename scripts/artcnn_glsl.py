"""ArtCNN (C4F16 / C4F32, any variant) ONNX -> mpv fragment-shader GLSL, plus an emulator.

Newer ArtCNN releases ship only compute shaders, which libplacebo's OpenGL ES backend
(Android) can't run. This regenerates the last fragment-shader layout of ArtCNN
(Artoriuz/ArtCNN d2f645a) from the current ONNX weights:

  conv0 (1->F) | conv1..4 (F->F, ReLU) | conv5 (F->F) | + conv0 skip | conv6 (F->4) | depth-to-space x2

Each pass computes 4 channels: result += mat4(W) * input_texOff(dx, dy).
`--half` makes the arithmetic mediump (fp16 on mobile GPUs, as ArtCNN's own compute shaders
use float16 when available); intermediate textures are 16-bit float either way.

  python3 scripts/artcnn_glsl.py gen  model.onnx "ArtCNN C4F16 DS" out.glsl [--half]
  python3 scripts/artcnn_glsl.py check model.onnx shader.glsl [image.png] [--half]
"""
import re
import sys

import numpy as np


def load_onnx(path):
    import onnx
    from onnx import numpy_helper
    m = onnx.load(path)
    init = {t.name: numpy_helper.to_array(t) for t in m.graph.initializer}
    convs = []
    for n in m.graph.node:
        if n.op_type == "Conv":
            pads = [a for a in n.attribute if a.name == "auto_pad"]
            assert pads and pads[0].s in (b"SAME_UPPER", b"SAME_LOWER"), "expected SAME padding"
            convs.append((init[n.input[1]].astype(np.float64), init[n.input[2]].astype(np.float64)))
    ops = [n.op_type for n in m.graph.node]
    assert ops == ["Conv", "Conv", "Relu", "Conv", "Relu", "Conv", "Relu", "Conv", "Relu", "Conv",
                   "Add", "Conv", "DepthToSpace", "Clip"], ops
    adds = [n for n in m.graph.node if n.op_type == "Add"][0]
    assert list(adds.input) == ["Conv_5", "Conv_0"], adds.input
    d2s = [n for n in m.graph.node if n.op_type == "DepthToSpace"][0]
    assert {a.name: a for a in d2s.attribute}["mode"].s == b"DCR"
    return convs


def f(x):
    s = "%.9g" % x
    return s if any(c in s for c in ".en") else s + ".0"


