WHEN = "//!WHEN OUTPUT.w LUMA.w / 1.3 > OUTPUT.h LUMA.h / 1.3 > *"


def generate(convs, name, half=False, onnx_name="", commit=""):
    F = convs[0][0].shape[0]
    G = F // 4
    p = "mediump " if half else ""
    out = [HEADER.format(name=name, onnx=onnx_name, commit=commit)]

    def header(desc, binds, save, scale=False):
        h = [f"//!DESC {name} ({desc})", "//!HOOK LUMA"] + [f"//!BIND {b}" for b in binds]
        if save:
            h.append(f"//!SAVE {save}")
        h += [f"//!WIDTH LUMA.w{' 2.0 *' if scale else ''}", f"//!HEIGHT LUMA.h{' 2.0 *' if scale else ''}",
              "//!COMPONENTS 4", WHEN, ""]
        return h

    def body(bias, terms, relu, temp=True):
        # mediump temp: texture reads are highp (scaled by a highp uniform); assigning them to a
        # mediump variable makes the multiply-adds run at half precision.
        use_temp = half and temp
        lines = ["vec4 hook() {", f"    {p if use_temp else ''}vec4 result = vec4({', '.join(f(b) for b in bias)});"]
        if use_temp:
            lines.append("    mediump vec4 t;")
        for coeff, expr in terms:
            if use_temp:
                lines.append(f"    t = {expr};")
                expr = "t"
            lines.append(f"    result += {coeff} * {expr};")
        lines.append("    return max(result, vec4(0.0));" if relu else "    return result;")
        return lines + ["}", ""]

    taps = [(kh, kw) for kh in range(3) for kw in range(3)]
    # conv0: 1 -> F, reads luma.
    w, b = convs[0]
    for og in range(G):
        terms = []
        for kh, kw in taps:
            v = "vec4(" + ", ".join(f(w[4 * og + r, 0, kh, kw]) for r in range(4)) + ")"
            terms.append((v, f"LUMA_texOff(vec2({kw - 1}, {kh - 1})).x"))
        out += header("Conv2D", ["LUMA"], f"conv2d_{og}") + body(b[4 * og:4 * og + 4], terms, False, temp=False)

    def name_of(layer, g):
        return f"conv2d_{g}" if layer == 0 else f"conv2d_{layer}_{g}"

    def mat(w, og, ig, kh, kw):
        # GLSL mat4 is column-major: column c = weights from input channel 4*ig+c.
        return "mat4(" + ", ".join(f(w[4 * og + r, 4 * ig + c, kh, kw]) for c in range(4) for r in range(4)) + ")"

    for layer in range(1, 6):
        w, b = convs[layer]
        relu = layer <= 4
        desc = f"Conv2D-{layer}" + ("-ReLU" if relu else "")
        for og in range(G):
            terms = [(mat(w, og, ig, kh, kw), f"{name_of(layer - 1, ig)}_texOff(vec2({kw - 1}, {kh - 1}))")
                     for ig in range(G) for kh, kw in taps]
            out += header(desc, [name_of(layer - 1, ig) for ig in range(G)], f"conv2d_{layer}_{og}") + \
                body(b[4 * og:4 * og + 4], terms, relu)

    # conv6: F -> 4 on (conv5 + conv0). It reads 2*G textures; GLSL ES only guarantees 16
    # texture units, so above 8 inputs it is split in halves (partial sum in conv2d_6_p).
    w, b = convs[6]

    def conv6_terms(groups):
        return [(mat(w, 0, ig, kh, kw),
                 f"({name_of(5, ig)}_texOff(vec2({kw - 1}, {kh - 1})) + {name_of(0, ig)}_texOff(vec2({kw - 1}, {kh - 1})))")
                for ig in groups for kh, kw in taps]

    def conv6_binds(groups):
        return [x for ig in groups for x in (name_of(0, ig), name_of(5, ig))]

    if 2 * G <= 8:
        out += header("Conv2D-6", conv6_binds(range(G)), "conv2d_6_0") + body(b, conv6_terms(range(G)), False)
    else:
        first, second = range(G // 2), range(G // 2, G)
        out += header("Conv2D-6 part 1/2", conv6_binds(first), "conv2d_6_p") + body(b, conv6_terms(first), False)
        part2 = body([0.0] * 4, conv6_terms(second), False)
        part2[1] = f"    {p}vec4 result = conv2d_6_p_tex(conv2d_6_p_pos);"
        out += header("Conv2D-6 part 2/2", conv6_binds(second) + ["conv2d_6_p"], "conv2d_6_0") + part2

    out += header("Depth-To-Space", ["conv2d_6_0"], None, scale=True) + [
        "vec4 hook() {",
        "    vec4 result = vec4(0.0, 0.0, 0.0, 1.0);",
        "    vec2 f0 = fract(conv2d_6_0_pos * conv2d_6_0_size);",
        "    ivec2 i0 = ivec2(f0 * vec2(2.0));",
        "    result.x = conv2d_6_0_tex((vec2(0.5) - f0) * conv2d_6_0_pt + conv2d_6_0_pos)[i0.y * 2 + i0.x];",
        "    return clamp(result, 0.0, 1.0);",
        "}",
        "",
    ]
    return "\n".join(out)


# --- emulator of the fragment-shader layout above (and of ArtCNN's own old shaders) --------

NUM = r"[-+0-9.eE]+"


def shift(t, dx, dy):
    """texOff(vec2(dx, dy)) with edge clamping: out[y, x] = t[y + dy, x + dx]."""
    H, W = t.shape[:2]
    ys = np.clip(np.arange(H) + dy, 0, H - 1)
    xs = np.clip(np.arange(W) + dx, 0, W - 1)
    return t[ys][:, xs]


def emulate(glsl, luma, half=False, swap_xy=False, transpose=False):
    dt = np.float16 if half else np.float64
    tex = {"LUMA": luma.astype(np.float64)}
    passes = re.split(r"(?=^//!DESC)", glsl, flags=re.M)[1:]
    for p in passes:
        save = re.search(r"^//!SAVE (\S+)", p, re.M)
        if "Depth-To-Space" in p:
            c = tex["conv2d_6_0"]
            H, W = c.shape[:2]
            out = np.zeros((2 * H, 2 * W))
            for i in range(2):
                for j in range(2):
                    out[i::2, j::2] = c[:, :, i * 2 + j]
            return np.clip(out, 0, 1)
        H, W = luma.shape
        init = re.search(r"vec4 result = (.*);", p).group(1)
        from_tex = re.fullmatch(r"(\w+)_tex\(\1_pos\)", init)
        if from_tex:
            result = tex[from_tex.group(1)].astype(dt)
        else:
            bias = [float(x) for x in re.fullmatch(r"vec4\(([^)]*)\)", init).group(1).split(",")]
            result = np.tile(np.array(bias, dtype=dt), (H, W, 1))
        # Pair "t = expr;" with the following "result += coeff * t;" when --half was used.
        stmts = re.findall(r"^\s*(t = .*|result \+= .*);$", p, re.M)
        pending = None
        for s in stmts:
            if s.startswith("t = "):
                pending = s[4:]
                continue
            m = re.match(r"result \+= (vec4|mat4)\(([^)]*)\) \* (.*)$", s)
            kind, coeffs, expr = m.group(1), [float(x) for x in m.group(2).split(",")], m.group(3)
            if expr == "t":
                expr = pending
            val = None
            for tname, dx, dy, comp in re.findall(r"(\w+)_texOff\(vec2\((" + NUM + "), (" + NUM + r")\)\)(\.x)?", expr):
                dx, dy = int(float(dx)), int(float(dy))
                if swap_xy:
                    dx, dy = dy, dx
                v = shift(tex[tname], dx, dy)
                v = v[..., None] if v.ndim == 2 else v
                v = v[..., :1] if comp else v
                val = v if val is None else val + v
            if kind == "vec4":
                term = np.asarray(coeffs, dtype=dt)[None, None, :] * val.astype(dt)
            else:
                M = np.asarray(coeffs).reshape(4, 4)  # [column][row]
                M = M if transpose else M.T           # -> [row][column]
                term = np.einsum("rc,hwc->hwr", M.astype(dt), val.astype(dt))
            result = (result + term).astype(dt)
        if re.search(r"return max\(result", p):
            result = np.maximum(result, 0)
        # Intermediate textures are 16-bit float in libplacebo.
        tex[save.group(1)] = result.astype(np.float16).astype(np.float64)
    raise ValueError("no depth-to-space pass")


def onnx_run(path, luma):
    import onnxruntime as ort
    s = ort.InferenceSession(path, providers=["CPUExecutionProvider"])
    return s.run(None, {"input": luma[None, None].astype(np.float32)})[0][0, 0].astype(np.float64)


def test_image(path=None):
    from PIL import Image
    if path:
        img = Image.open(path).convert("L")
    else:
        rng = np.random.default_rng(1)
        img = Image.fromarray((rng.random((48, 64)) * 255).astype(np.uint8)).resize((128, 96))
    return np.asarray(img, dtype=np.float64) / 255.0


def psnr(a, b):
    return 10 * np.log10(1.0 / max(np.mean((a - b) ** 2), 1e-20))


if __name__ == "__main__":
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    half = "--half" in sys.argv
    if args[0] == "gen":
        _, model, name, dest = args[:4]
        commit = args[4] if len(args) > 4 else ""
        open(dest, "w").write(generate(load_onnx(model), name, half, model.split("/")[-1], commit))
    elif args[0] == "check":
        _, model, shader = args[:3]
        luma = test_image(args[3] if len(args) > 3 else None)
        ref = onnx_run(model, luma)
        glsl = open(shader).read()
        b = 4  # ignore borders: ONNX pads with zeros, textures clamp to the edge
        for label, kw in [("as written", {}), ("x/y swapped", {"swap_xy": True}), ("matrix transposed", {"transpose": True})]:
            out = emulate(glsl, luma, half=half, **kw)
            print(f"{label:18} PSNR vs ONNX {psnr(out[b:-b, b:-b], ref[b:-b, b:-b]):6.1f} dB  "
                  f"max |diff| {np.abs(out[b:-b, b:-b] - ref[b:-b, b:-b]).max():.5f}")
